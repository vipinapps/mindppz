// Build step:
//   1. Bundle the Firebase SDK into public/js/vendor/firebase.js (no CDN needed).
//   2. Generate firestore.rules from the survey definition, so the database only
//      accepts answers in exactly the format the survey allows.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { survey, OTHER_MAX } from '../public/js/survey-data.js';

const root = fileURLToPath(new URL('..', import.meta.url));

await build({
  entryPoints: [`${root}src/firebase-entry.js`],
  outfile: `${root}public/js/vendor/firebase.js`,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'eof',
  logLevel: 'warning',
});
console.log('Bundled public/js/vendor/firebase.js');

// ---------------------------------------------------------------------------
const list = (arr) => `[${arr.map((s) => `'${s}'`).join(', ')}]`;
const qids = survey.questions.map((q) => q.id);

function questionRule(q) {
  const fn = `valid_${q.id}`;
  if (q.type === 'text') {
    return `    function ${fn}(a) {
      return a is map && a.keys().hasOnly(['text']) && a.text is string
        && a.text.size() >= 1 && a.text.size() <= ${q.maxLength};
    }`;
  }
  const ids = q.options.map((o) => o.id);
  const max = q.type === 'single' ? 1 : q.max || ids.length;
  const other = q.options.find((o) => o.other);
  const otherClause = other
    ? `
        && (('${other.id}' in a.selected
              && a.keys().hasOnly(['selected', 'other']) && a.other is string
              && a.other.size() >= 1 && a.other.size() <= ${OTHER_MAX})
            || (!('${other.id}' in a.selected) && a.keys().hasOnly(['selected'])))`
    : `
        && a.keys().hasOnly(['selected'])`;
  return `    // ${q.id}: ${q.type === 'single' ? 'single choice' : `multi choice, max ${max}`}
    function ${fn}(a) {
      return a is map && a.selected is list
        && a.selected.size() >= 1 && a.selected.size() <= ${max}
        && a.selected.toSet().size() == a.selected.size()
        && a.selected.toSet().hasOnly(${list(ids)})${otherClause};
    }`;
}

const rules = `rules_version = '2';

// GENERATED by scripts/build.js from public/js/survey-data.js. Do not edit by hand:
// change the survey definition and run \`npm run build\`.
//
// Collections:
//   users/{uid}      profile of each Google user who signed in (admin can list)
//   responses/{uid}  that user's survey answers (one per user, updatable)
//   admins/{uid}     marks a Firebase Auth account as admin. Create it in the
//                    Firebase console only; no client can write it.

service cloud.firestore {
  match /databases/{database}/documents {

    function signedIn() {
      return request.auth != null;
    }

    function isAdmin() {
      return signedIn() && exists(/databases/$(database)/documents/admins/$(request.auth.uid));
    }

    // Respondents must be the owner of the document and signed in with Google.
    function isGoogleUser(uid) {
      return signedIn() && request.auth.uid == uid
        && request.auth.token.firebase.sign_in_provider == 'google.com'
        && request.auth.token.email_verified == true;
    }

    function validProfile(d) {
      return d.email == request.auth.token.email
        && d.name is string && d.name.size() <= 200
        && d.picture is string && d.picture.size() <= 2000;
    }

${survey.questions.map(questionRule).join('\n\n')}

    function validAnswers(a) {
      return a is map && a.keys().hasOnly(${list(qids)}) && a.keys().hasAll(${list(qids)})
${qids.map((id) => `        && valid_${id}(a.${id})`).join('\n')};
    }

    function validResponse(d) {
      return d.keys().hasOnly(['email', 'name', 'picture', 'answers', 'submittedAt', 'updatedAt', 'edits'])
        && d.keys().hasAll(['email', 'name', 'picture', 'answers', 'submittedAt', 'updatedAt', 'edits'])
        && validProfile(d) && validAnswers(d.answers) && d.edits is int;
    }

    match /users/{uid} {
      allow get: if isGoogleUser(uid) || isAdmin();
      allow list: if isAdmin();
      allow create: if isGoogleUser(uid)
        && request.resource.data.keys().hasOnly(['email', 'name', 'picture', 'firstLoginAt', 'lastLoginAt'])
        && request.resource.data.keys().hasAll(['email', 'name', 'picture', 'firstLoginAt', 'lastLoginAt'])
        && validProfile(request.resource.data)
        && request.resource.data.firstLoginAt == request.time
        && request.resource.data.lastLoginAt == request.time;
      allow update: if isGoogleUser(uid)
        && request.resource.data.keys().hasOnly(['email', 'name', 'picture', 'firstLoginAt', 'lastLoginAt'])
        && request.resource.data.keys().hasAll(['email', 'name', 'picture', 'firstLoginAt', 'lastLoginAt'])
        && validProfile(request.resource.data)
        && request.resource.data.firstLoginAt == resource.data.firstLoginAt
        && request.resource.data.lastLoginAt == request.time;
      allow delete: if isAdmin();
    }

    match /responses/{uid} {
      allow get: if isGoogleUser(uid) || isAdmin();
      allow list: if isAdmin();
      allow create: if isGoogleUser(uid) && validResponse(request.resource.data)
        && request.resource.data.submittedAt == request.time
        && request.resource.data.updatedAt == request.time
        && request.resource.data.edits == 0;
      allow update: if isGoogleUser(uid) && validResponse(request.resource.data)
        && request.resource.data.submittedAt == resource.data.submittedAt
        && request.resource.data.updatedAt == request.time
        && request.resource.data.edits == resource.data.edits + 1;
      allow delete: if isAdmin();
    }

    match /admins/{uid} {
      allow get: if signedIn() && request.auth.uid == uid;
      allow list, write: if false;
    }

    // Everything else is closed.
    match /{document=**} {
      allow read, write: if false;
    }
  }
}
`;
writeFileSync(`${root}firestore.rules`, rules);
console.log('Generated firestore.rules');
